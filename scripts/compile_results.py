"""
Compiles evaluation results into paper-ready tables, figures and a JSON record.

Inputs
  data/eval/runs/*.json        run artifacts from scripts/run_evaluation.py
  data/guardrail.db            audit log (retrieval decisions, stage timings)
  data/ground_truth/pii_labels.json
  data/eval/attack_corpus.json
  data/mock_docs/*.txt         for the offline redaction benchmark

Outputs, into paper/generated/
  tab_*.tex    IEEE-style tables, \\input{} them - never hand-edit
  tab_*.csv    the same numbers for checking
  fig_*.pdf    vector figures (only if matplotlib is available)
  results.json every computed metric, so prose claims can be checked
  manifest.json  git SHA, inputs, timestamps, sample sizes

Design rule: a cell with too few observations prints "n<K" rather than a
number. A table full of confident-looking figures computed from two runs is
how a paper gets a reviewer asking for the sample size - better to say so.

Run from the repo root. Preferably inside the container, so it sees the same
filesystem and package versions as the system under test:
    docker-compose run --rm api python scripts/compile_results.py
"""
