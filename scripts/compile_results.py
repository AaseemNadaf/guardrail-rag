CLASSIFICATION_ORDER = ["Public", "Internal", "Confidential", "Restricted"]


# ----------------------------------------------------------------- helpers

def rate(num, den, min_n=MIN_N):
    """A proportion, or an explicit insufficiency marker. Never a bare number."""
    if den == 0:
        return {"value": None, "n": 0, "display": "—"}
    if den < min_n:
        return {"value": num / den, "n": den, "display": f"n={den}, insufficient"}
    return {"value": num / den, "n": den, "display": f"{num/den:.1%} ({num}/{den})"}


def stat_block(values, unit="ms"):
    vals = [v for v in values if v is not None]
    if not vals:
        return {"n": 0, "display": "—"}
    if len(vals) < MIN_N:
        return {"n": len(vals), "median": statistics.median(vals),
                "display": f"n={len(vals)}, insufficient"}
    p95 = sorted(vals)[max(0, int(round(0.95 * len(vals))) - 1)]
    return {
        "n": len(vals),
        "median": statistics.median(vals),
        "p95": p95,
        "mean": statistics.fmean(vals),
        "display": f"{statistics.median(vals):.0f} / {p95:.0f} {unit}",
    }


def tex_escape(s):
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("_", r"\_"),
                 ("#", r"\#"), ("$", r"\$"), ("{", r"\{"), ("}", r"\}"),
                 ("<", r"\textless{}"), (">", r"\textgreater{}")]:
        s = s.replace(a, b)
    return s


def write_table(name, caption, headers, rows, note=None):
    os.makedirs(OUT_DIR, exist_ok=True)
    col = "l" + "r" * (len(headers) - 1)
    lines = [
        "% GENERATED by scripts/compile_results.py - do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        f"\\caption{{{tex_escape(caption)}}}",
        f"\\label{{tab:{name}}}",
        f"\\begin{{tabular}}{{{col}}}", "\\toprule",
        " & ".join(f"\\textbf{{{tex_escape(h)}}}" for h in headers) + " \\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append(" & ".join(tex_escape(str(c)) for c in r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if note:
        lines.append(f"\\vspace{{2pt}}\\footnotesize{{{tex_escape(note)}}}")
    lines.append("\\end{table}")
    with open(f"{OUT_DIR}/tab_{name}.tex", "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    import csv
    with open(f"{OUT_DIR}/tab_{name}.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(headers)
        w.writerows(rows)


# ----------------------------------------------------------------- loaders

def load_runs():
    runs = []
    for p in sorted(glob.glob(RUNS_GLOB)):
        with open(p, encoding="utf-8") as fh:
            d = json.load(fh)
        d["_path"] = p
        runs.append(d)
    return runs


def load_audit():
    if not os.path.exists(AUDIT_DB):
        return []
    import sqlite3
    con = sqlite3.connect(f"file:{AUDIT_DB}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row
    try:
        rows = [dict(r) for r in con.execute("SELECT * FROM audit_log ORDER BY timestamp")]
    except sqlite3.Error as e:
        print(f"  WARNING: could not read audit log ({e}); audit-derived tables will be empty")
        rows = []
    finally:
        con.close()
    for r in rows:
        r["retrieved_docs"] = json.loads(r["retrieved_docs"]) if r.get("retrieved_docs") else []
    return rows


def load_corpus():
    """Corpus cases keyed by (prompt, user) - the pair that identifies a case."""
    if not os.path.exists(CORPUS_PATH):
        return {}
    cases = json.load(open(CORPUS_PATH, encoding="utf-8"))["cases"]
    return {(c["prompt"], c["as_user"]): c for c in cases}


def condition_info(runs):
    """Per-condition toggles, from the /health snapshot each run file recorded."""
    info = {}
    for run in runs:
        h = run["_meta"].get("health") or {}
        info.setdefault(run["_meta"]["condition"], {
            "rbac_filter": h.get("rbac_filter"),
            "relevance_floor": h.get("relevance_floor"),
            "similarity_cutoff": h.get("similarity_cutoff"),
        })
    return info


def rbac_enabled(cond, info):
    """True / False if known; None if neither the run file nor the label says."""
    v = (info.get(cond) or {}).get("rbac_filter")
    if v is not None:
        return bool(v)
    if "rbac=1" in cond:
        return True
    if "rbac=0" in cond:
        return False
    return None


def corpus_rows(audit, corpus):
    """
    Audit rows that belong to a corpus case, matched on (question, username).

    Matching on the question alone is not enough: the runner's warmup query
    reuses a benign prompt (BEN-08) but is sent as a different user, and would
    otherwise be scored as that case - under the wrong clearance.
    """
    out = []
    for r in audit:
        case = corpus.get((r["question"], r["username"]))
        if case:
            out.append({**r, "case": case})
    return out


def collapse_audit(rows):
    """
    One row per (condition, corpus case), however many times it was run.

    Repeating the corpus does not multiply the evidence. Retrieval is
    deterministic and the prompts are identical, so counting each repetition
    as a fresh observation is pseudo-replication: n inflates and every rate
    looks more certain than it is. Security tables therefore count each case
    once, and score it worst-case - refused, Layer-3-caught or ungrounded if
    ANY repetition was. Latency is the exception; repetitions are genuine
    timing samples, so it uses corpus_rows() directly.
    """
    merged = {}
    for r in rows:
        k = (r.get("condition") or "unknown", r["case"]["id"])
        m = merged.get(k)
        if m is None:
            merged[k] = {**r, "reps": 1}
            continue
        m["reps"] += 1
        if r["refused"] and not m["refused"]:
            m["refused"], m["refusal_reason"] = r["refused"], r["refusal_reason"]
        m["pii_redacted"] = bool(m["pii_redacted"]) or bool(r["pii_redacted"])
        if r["grounded"] is not None:
            m["grounded"] = r["grounded"] if m["grounded"] is None else (m["grounded"] and r["grounded"])
        if not m["retrieved_docs"] and r["retrieved_docs"]:
            m["retrieved_docs"] = r["retrieved_docs"]
    return list(merged.values())


